create extension if not exists pgcrypto;

create table if not exists public.home_banners (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 1 and 120),
  message text,
  style text not null default 'info'
    check (style in ('info', 'important', 'success')),
  icon_name text not null default 'campaign',
  action_type text not null default 'none'
    check (action_type in ('none', 'internal', 'url', 'pdf', 'news')),
  action_value text,
  action_label text,
  audiences text[] not null default array['all']::text[],
  platforms text[] not null default array['all']::text[],
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default false,
  is_dismissible boolean not null default true,
  sort_order integer not null default 100,
  image_storage_path text,
  archived_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint home_banners_dates_ok check (
    ends_at is null or starts_at is null or ends_at > starts_at
  ),
  constraint home_banners_action_ok check (
    action_type = 'none' or nullif(btrim(action_value), '') is not null
  )
);

create index if not exists home_banners_live_idx
  on public.home_banners (is_active, archived_at, sort_order, starts_at, ends_at);

create table if not exists public.home_banner_events (
  id bigint generated by default as identity primary key,
  banner_id uuid not null references public.home_banners(id) on delete cascade,
  event_type text not null check (event_type in ('impression', 'click', 'dismiss')),
  user_id uuid references auth.users(id) on delete set null default auth.uid(),
  session_id text not null check (char_length(session_id) between 8 and 120),
  platform text not null,
  created_at timestamptz not null default now()
);

create index if not exists home_banner_events_banner_created_idx
  on public.home_banner_events (banner_id, created_at desc);
create index if not exists home_banner_events_type_created_idx
  on public.home_banner_events (event_type, created_at desc);

create or replace function public.touch_home_banner_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  new.updated_by = auth.uid();
  return new;
end;
$$;

drop trigger if exists trg_home_banners_updated_at on public.home_banners;
create trigger trg_home_banners_updated_at
before update on public.home_banners
for each row execute function public.touch_home_banner_updated_at();

-- Adapte ici les niveaux si votre table public.users utilise d'autres valeurs.
-- Les valeurs connues de l'app sont adm / supuser ; admin / superadmin sont tolérées.
create or replace function public.is_home_banner_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    exists (
      select 1
      from public.users u
      where u.id = auth.uid()
        and lower(coalesce(u.level::text, ''))
          in ('adm', 'admin', 'supuser', 'superadmin')
    )
    or exists (
      select 1
      from public.users u
      join public.role_table r
        on r.matricule::text = u.matriculeaf::text
      where u.id = auth.uid()
        and lower(coalesce(r.role::text, ''))
          in ('adm', 'admin', 'supuser', 'superadmin')
    );
$$;

revoke all on function public.is_home_banner_admin() from public;
grant execute on function public.is_home_banner_admin() to authenticated;

