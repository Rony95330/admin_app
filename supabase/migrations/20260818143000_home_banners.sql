-- Lecture publique : uniquement les bandeaux effectivement diffusables.
-- audiences/platforms restent un ciblage d'affichage, pas une frontière de sécurité.
drop policy if exists home_banners_public_read_live on public.home_banners;
create policy home_banners_public_read_live
on public.home_banners
for select
to anon, authenticated
using (
  is_active = true
  and archived_at is null
  and (starts_at is null or starts_at <= now())
  and (ends_at is null or ends_at > now())
);

