-- Petite fonction RPC d'analytics agrégées, réservée admin.
create or replace function public.home_banner_stats(p_banner_id uuid)
returns table (
  impressions bigint,
  clicks bigint,
  dismissals bigint,
  click_rate numeric
)
language sql
stable
security definer
set search_path = public
as $$
  select
    count(*) filter (where e.event_type = 'impression') as impressions,
    count(*) filter (where e.event_type = 'click') as clicks,
    count(*) filter (where e.event_type = 'dismiss') as dismissals,
    case
      when count(*) filter (where e.event_type = 'impression') = 0 then 0::numeric
      else round(
        100.0 * count(*) filter (where e.event_type = 'click')
        / count(*) filter (where e.event_type = 'impression'),
        2
      )
    end as click_rate
  from public.home_banner_events e
  where e.banner_id = p_banner_id
    and public.is_home_banner_admin();
$$;

revoke all on function public.home_banner_stats(uuid) from public;
grant execute on function public.home_banner_stats(uuid) to authenticated;
